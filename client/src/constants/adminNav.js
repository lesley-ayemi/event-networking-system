// "/admin" (Dashboard) is a path prefix of every other admin route, so it
// needs an exact match — otherwise it stays highlighted/matched no matter
// which admin page is actually open. Shared by the sidebar's active-link
// styling and the topbar's page title so the two can't drift out of sync.
export function matchesAdminLink(currentPath, linkTo) {
  if (linkTo === "/admin") {
    return currentPath === "/admin";
  }
  return currentPath === linkTo || currentPath.startsWith(`${linkTo}/`);
}

